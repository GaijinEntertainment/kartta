const MARKERS: [&[u8]; 3] = [b"@generated", b"DO NOT EDIT", b"Code generated"];
const BYTE_ORDER_MARK: &[u8] = b"\xEF\xBB\xBF";

pub(crate) fn is_generated_source(source: &[u8]) -> bool {
    let source = source.strip_prefix(BYTE_ORDER_MARK).unwrap_or(source);
    let mut in_block = false;

    for raw in source.split(|byte| *byte == b'\n') {
        let mut line = raw.trim_ascii();

        if in_block {
            let end = block_close(line);
            if marks_generated(&line[..end.unwrap_or(line.len())]) {
                return true;
            }
            let Some(end) = end else {
                continue;
            };
            in_block = false;
            line = line[end + 2..].trim_ascii();
        }

        match leading_comments(line) {
            Header::Generated => return true,
            Header::Ended => return false,
            Header::InBlock => in_block = true,
            Header::Continues => {}
        }
    }

    false
}

enum Header {
    Generated,
    Ended,
    InBlock,
    Continues,
}

fn leading_comments(mut line: &[u8]) -> Header {
    loop {
        if line.is_empty() {
            return Header::Continues;
        }
        if line.starts_with(b"//") {
            return if marks_generated(line) {
                Header::Generated
            } else {
                Header::Continues
            };
        }
        if !line.starts_with(b"/*") {
            return Header::Ended;
        }

        let Some(end) = block_close(&line[2..]) else {
            return if marks_generated(line) {
                Header::Generated
            } else {
                Header::InBlock
            };
        };
        let comment_end = 2 + end + 2;
        if marks_generated(&line[..comment_end]) {
            return Header::Generated;
        }
        line = line[comment_end..].trim_ascii();
    }
}

fn block_close(text: &[u8]) -> Option<usize> {
    text.windows(2).position(|window| window == b"*/")
}

fn marks_generated(line: &[u8]) -> bool {
    MARKERS.iter().any(|marker| announces(line, marker))
}

fn announces(line: &[u8], marker: &[u8]) -> bool {
    let mut in_span = false;
    for (at, byte) in line.iter().enumerate() {
        if !in_span && line[at..].starts_with(marker) {
            return true;
        }
        if *byte == b'`' {
            in_span = !in_span;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn each_leading_comment_marker_announces_generated_code() {
        let at_generated = b"// @generated by tool\noptions gen2\n";
        let do_not_edit = b"// DO NOT EDIT\noptions gen2\n";
        let code_generated = b"// Code generated by tool.\noptions gen2\n";
        let in_block = b"/*\n * DO NOT EDIT.\n */\noptions gen2\n";

        for source in [&at_generated[..], do_not_edit, code_generated, in_block] {
            assert!(
                is_generated_source(source),
                "{}",
                String::from_utf8_lossy(source)
            );
        }
        assert!(!is_generated_source(b"\noptions gen2\n"));
    }

    #[test]
    fn a_byte_order_mark_does_not_hide_the_banner() {
        assert!(is_generated_source(
            b"\xEF\xBB\xBF// @generated by tool\noptions gen2\n"
        ));
        assert!(is_generated_source(
            b"\xEF\xBB\xBF/* DO NOT EDIT */\noptions gen2\n"
        ));
        assert!(!is_generated_source(b"\xEF\xBB\xBFoptions gen2\n"));
    }

    #[test]
    fn a_header_that_quotes_a_marker_only_mentions_it() {
        let mention = b"/*\n * Files carrying a `@generated` or `DO NOT EDIT` header are machine output.\n */\n\
                        options gen2\n";
        let quoted_tool = b"// Code generated by `gen.exe`. DO NOT EDIT.\noptions gen2\n";

        assert!(!is_generated_source(mention));
        assert!(is_generated_source(quoted_tool));
    }

    #[test]
    fn a_marker_after_code_on_the_closing_line_is_no_header() {
        let block_closed_by_code =
            b"/*\n * module header\n */ options gen2\n// DO NOT EDIT\ndef f() {}\n";
        let inline_block_then_code = b"/* header */ options gen2\n// DO NOT EDIT\ndef f() {}\n";
        let marker_in_code = b"/* header */ let TAG = \"DO NOT EDIT\"\n";
        let marker_in_block = b"/* @generated by tool */\noptions gen2\n";
        let marker_after_block = b"/* license */ // @generated by tool\noptions gen2\n";

        assert!(!is_generated_source(block_closed_by_code));
        assert!(!is_generated_source(inline_block_then_code));
        assert!(!is_generated_source(marker_in_code));
        assert!(is_generated_source(marker_in_block));
        assert!(is_generated_source(marker_after_block));
    }

    #[test]
    fn a_marker_after_a_closed_span_still_announces() {
        assert!(announces(b"// see `docs.md`: @generated", b"@generated"));
        assert!(!announces(b"// see `docs.md: @generated", b"@generated"));
        assert!(!announces(b"// an ordinary header", b"@generated"));
    }
}
