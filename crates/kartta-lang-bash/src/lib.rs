//! Bash for the kartta code graph: the functions, aliases, globals and commands of a shell script, and the files it
//! sources.
//!
//! [`Bash`] implements [`Language`] over the `tree-sitter-bash` grammar. It claims every file whose extension is `sh`
//! or `bash`, in any case.
//!
//! # What a file extracts to
//!
//! Every function definition is a function symbol, and so is every name an `alias name=value` defines; every variable
//! assigned outside every function, bare or behind `export`, `declare`, `readonly` or `typeset`, in an `if` or a loop
//! too, is a variable symbol. An assignment that prefixes a command, `LANG=C sort`, or one inside a function, which
//! runs only with the function, is no symbol. Bash has no namespaces, so a symbol's qualified name is its name, and
//! every symbol is exported.
//!
//! Every command is a call of its name, attributed to the function around it — a subshell, a loop, a `case` arm or a
//! command substitution opens no scope of its own. A command made before the script defines anything is dropped, and
//! a command after that outside every function is a call from file scope. `alias` with definitions, `source` and `.`
//! are no calls.
//!
//! A `source` or `.` whose argument is literal — a word, a quoted string, or the literal tail after the expansions it
//! starts with, as in `"$DIR/lib/x.sh"` or `"$DIR"/lib/x.sh` — is a directive for the resolver; an argument computed
//! at run time alone, or one with an expansion after a literal part, names nothing.
//!
//! # Resolution
//!
//! A sourced path that starts with `./` or `../` names a file relative to the sourcing script, and any other names one
//! from the root of the repository, or else the only file whose path ends in it at a path segment; each is probed
//! as written, then with `.sh` and with `.bash`, and a suffix that two files match under any of those spellings names
//! none. A path that names no file of the repository adds no include.
//!
//! A file named `*_test.sh`, `*_test.bash` or `test_*`, or below a `test` or `tests` directory, is test code. A
//! `@generated`, `DO NOT EDIT` or `generated by` marker in the comments that open the file, outside a backtick span,
//! marks it generated. A function named `main` at the top of the script is its entry point.
//!
//! # Fingerprint
//!
//! [`Bash::fingerprint`] identifies this crate's name and version, a digest of its source, and the grammar: its
//! version, ABI version, node types, and the counts of its node kinds, parse states and fields. A change to
//! `kartta-lang` is covered by `kartta_lang::FINGERPRINT`, which a cache keys beside it. It cannot see a grammar built
//! from changed sources that keep its version and tables, nor a change to the tree-sitter runtime that keeps its
//! version.
//!
//! # Examples
//!
//! ```
//! use kartta_lang::Language;
//! use kartta_lang_bash::Bash;
//!
//! let bash = Bash::new();
//! assert!(bash.claims("scripts/deploy.sh"));
//!
//! let raw = bash.extract(b"deploy() {\n    rsync -a src/ dst/\n}\n");
//! let names: Vec<&str> = raw.symbols.iter().map(|symbol| symbol.name.as_str()).collect();
//! assert_eq!(names, ["deploy"]);
//! assert_eq!(raw.calls[0].callee, "rsync");
//! ```

use kartta_lang::path::base;
use kartta_lang::{DocComments, Language, RawExtraction, Repository, Resolver};

use crate::resolve::Sources;

mod resolve;
mod walk;

/// The Bash language.
#[derive(Debug, Clone, Copy, Default)]
#[non_exhaustive]
pub struct Bash;

impl Bash {
    /// The Bash language.
    #[must_use]
    pub const fn new() -> Self {
        Self
    }
}

impl Language for Bash {
    fn name(&self) -> &'static str {
        "bash"
    }

    fn claims(&self, path: &str) -> bool {
        base(path).rsplit_once('.').is_some_and(|(_, extension)| {
            extension.eq_ignore_ascii_case("sh") || extension.eq_ignore_ascii_case("bash")
        })
    }

    fn fingerprint(&self) -> &[u8] {
        kartta_lang::tree_sitter_fingerprint!(grammar(), tree_sitter_bash::NODE_TYPES)
    }

    fn doc_comments(&self) -> DocComments {
        DocComments::lines(&["#"])
    }

    fn extract(&self, source: &[u8]) -> RawExtraction {
        kartta_lang::tree::extract(&grammar(), source, walk::raw_walk)
    }

    fn resolver<'r>(&'r self, repository: &'r dyn Repository) -> Box<dyn Resolver + 'r> {
        Box::new(Sources { repository })
    }
}

fn grammar() -> tree_sitter::Language {
    tree_sitter_bash::LANGUAGE.into()
}
