const MARKERS: [&[u8]; 2] = [b"@generated", b"DO NOT EDIT"];

const SCRIPT_EXTENSIONS: [&str; 11] = [
    ".d.ts", ".d.mts", ".d.cts", ".tsx", ".ts", ".mts", ".cts", ".jsx", ".js", ".mjs", ".cjs",
];

enum HeaderLine {
    Generated,
    Comment { block_open: bool },
    Code,
}

pub(crate) fn is_generated_source(source: &[u8]) -> bool {
    let mut block_open = false;

    for line in source.split(|&byte| byte == b'\n') {
        match header_line(line.trim_ascii(), block_open) {
            HeaderLine::Generated => return true,
            HeaderLine::Comment { block_open: open } => block_open = open,
            HeaderLine::Code => return false,
        }
    }

    false
}

fn header_line(mut line: &[u8], block_open: bool) -> HeaderLine {
    if block_open {
        let Some(close) = find(line, b"*/") else {
            return comment(line, true);
        };
        if marks_generated(&line[..close]) {
            return HeaderLine::Generated;
        }
        line = line[close + 2..].trim_ascii();
    }

    if line.is_empty() {
        return HeaderLine::Comment { block_open: false };
    }
    if line.starts_with(b"//") {
        return comment(line, false);
    }
    let Some(body) = line.strip_prefix(b"/*") else {
        return HeaderLine::Code;
    };
    let Some(close) = find(body, b"*/") else {
        return comment(line, true);
    };

    let block_end = close + 4;
    if marks_generated(&line[..block_end]) {
        HeaderLine::Generated
    } else if line[block_end..].trim_ascii().is_empty() {
        HeaderLine::Comment { block_open: false }
    } else {
        HeaderLine::Code
    }
}

fn comment(text: &[u8], block_open: bool) -> HeaderLine {
    if marks_generated(text) {
        HeaderLine::Generated
    } else {
        HeaderLine::Comment { block_open }
    }
}

fn marks_generated(comment: &[u8]) -> bool {
    MARKERS.iter().any(|marker| announces(comment, marker))
}

fn announces(line: &[u8], marker: &[u8]) -> bool {
    if marker.is_empty() {
        return false;
    }

    (line.windows(marker.len()).enumerate())
        .filter(|(_, window)| *window == marker)
        .any(|(at, _)| {
            line[..at]
                .iter()
                .fold(true, |outside_span, &byte| outside_span ^ (byte == b'`'))
        })
}

fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack
        .windows(needle.len())
        .position(|window| window == needle)
}

pub(crate) fn name_marks_generated(name: &str) -> bool {
    if name.contains(".gen.") || name.contains(".generated.") {
        return true;
    }
    let stem = SCRIPT_EXTENSIONS
        .iter()
        .find_map(|extension| {
            let at = name.len().checked_sub(extension.len())?;
            let suffix = name.get(at..)?;
            suffix.eq_ignore_ascii_case(extension).then(|| &name[..at])
        })
        .unwrap_or(name);
    stem.strip_suffix("pb")
        .is_some_and(|rest| rest.ends_with(['_', '.']))
        || stem
            .strip_suffix("min")
            .is_some_and(|rest| rest.ends_with('.'))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_marker_name_counts_whatever_case_the_extension_is_in() {
        assert!(name_marks_generated("schema_pb.TS"));
        assert!(name_marks_generated("vendor.min.JS"));
        assert!(!name_marks_generated("schema.TS"));
    }

    #[test]
    fn a_banner_announces_even_when_the_line_quotes_something_else() {
        assert!(announces(
            b"// Code generated by `gen.exe`. DO NOT EDIT.",
            b"DO NOT EDIT"
        ));
        assert!(announces(
            b"// Code generated by protoc-gen-go. DO NOT EDIT.",
            b"DO NOT EDIT"
        ));
        assert!(announces(
            b"/* Automatically @generated by tree-sitter */",
            b"@generated"
        ));
        assert!(announces(b"# @generated", b"@generated"));
    }

    #[test]
    fn a_quoted_marker_only_mentions() {
        let mention = b"//! a `@generated` / `DO NOT EDIT` marker in the leading comment run";

        assert!(!announces(mention, b"@generated"));
        assert!(!announces(mention, b"DO NOT EDIT"));
        assert!(!announces(
            b"//! every symbol test code, a `// Code generated ... DO NOT EDIT.` header",
            b"Code generated"
        ));
    }

    #[test]
    fn a_marker_after_a_closed_span_still_announces() {
        assert!(announces(b"// see `docs.md`: @generated", b"@generated"));
        assert!(!announces(b"// see `docs.md: @generated", b"@generated"));
    }

    #[test]
    fn a_line_without_the_marker_never_announces() {
        assert!(!announces(b"// an ordinary header", b"@generated"));
        assert!(!announces(b"", b"@generated"));
        assert!(!announces(b"// @generated", b""));
    }
}
