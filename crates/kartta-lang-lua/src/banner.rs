const MARKERS: [&[u8]; 2] = [b"@generated", b"DO NOT EDIT"];
const BYTE_ORDER_MARK: &[u8] = b"\xEF\xBB\xBF";

enum HeaderLine {
    Generated,
    Comment,
    OpensLongComment { level: usize },
    Code,
}

// constraint: the header is the leading run of blank lines, a `#!` shebang, `--` comments and `--[[ ]]` long comments
// of any level, `--[==[ ]==]`, after a byte order mark that Lua skips; the first code ends the scan, and a marker
// counts only in comment text, never in code after the comment closes
pub(crate) fn is_generated_source(source: &[u8]) -> bool {
    let source = source.strip_prefix(BYTE_ORDER_MARK).unwrap_or(source);
    let mut open_level = None;
    for line in source.split(|&byte| byte == b'\n') {
        let mut line = line.trim_ascii();
        if let Some(level) = open_level {
            let (comment, after) = comment_and_code_after_close(line, level);
            if announces_generated(comment) {
                return true;
            }
            let Some(after) = after else {
                continue;
            };
            open_level = None;
            line = after;
        }

        match header_line(line) {
            HeaderLine::Generated => return true,
            HeaderLine::Code => return false,
            HeaderLine::OpensLongComment { level } => open_level = Some(level),
            HeaderLine::Comment => {}
        }
    }

    false
}

fn header_line(mut line: &[u8]) -> HeaderLine {
    loop {
        if line.is_empty() || line.starts_with(b"#!") {
            return HeaderLine::Comment;
        }
        let Some(comment) = line.strip_prefix(b"--") else {
            return HeaderLine::Code;
        };
        let Some((level, body)) = long_comment_open(comment) else {
            return marked(line, HeaderLine::Comment);
        };
        let Some(end) = long_comment_end(body, level) else {
            return marked(line, HeaderLine::OpensLongComment { level });
        };

        if announces_generated(&body[..end]) {
            return HeaderLine::Generated;
        }
        line = body[end + level + 2..].trim_ascii();
    }
}

fn marked(comment: &[u8], unmarked: HeaderLine) -> HeaderLine {
    if announces_generated(comment) {
        HeaderLine::Generated
    } else {
        unmarked
    }
}

fn comment_and_code_after_close(line: &[u8], level: usize) -> (&[u8], Option<&[u8]>) {
    long_comment_end(line, level).map_or((line, None), |end| {
        (&line[..end], Some(line[end + level + 2..].trim_ascii()))
    })
}

// constraint: a long comment opens with `[`, its level of `=`, and `[`; any other `--[` starts a line comment
fn long_comment_open(comment: &[u8]) -> Option<(usize, &[u8])> {
    let rest = comment.strip_prefix(b"[")?;
    let level = rest.iter().take_while(|&&byte| byte == b'=').count();

    Some((level, rest[level..].strip_prefix(b"[")?))
}

fn long_comment_end(text: &[u8], level: usize) -> Option<usize> {
    text.windows(level + 2).position(|window| {
        window[0] == b']'
            && window[level + 1] == b']'
            && window[1..=level].iter().all(|&byte| byte == b'=')
    })
}

// constraint: a marker inside a backtick span documents the convention rather than claiming this file follows it
fn announces_generated(line: &[u8]) -> bool {
    let mut outside_span = true;
    for (at, &byte) in line.iter().enumerate() {
        if byte == b'`' {
            outside_span = !outside_span;
        } else if outside_span && MARKERS.iter().any(|marker| line[at..].starts_with(marker)) {
            return true;
        }
    }

    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_quoted_marker_only_mentions_the_convention() {
        assert!(is_generated_source(
            b"-- @generated by tooling\nreturn {}\n"
        ));
        assert!(!is_generated_source(
            b"-- a `@generated` marker\nreturn {}\n"
        ));
        assert!(is_generated_source(
            b"-- see `docs.md`: DO NOT EDIT\nreturn {}\n"
        ));
        assert!(is_generated_source(
            b"-- the `@generated` marker: @generated\nreturn {}\n"
        ));
    }

    #[test]
    fn a_byte_order_mark_leaves_the_header_in_place() {
        assert!(is_generated_source(
            b"\xEF\xBB\xBF-- @generated\nreturn {}\n"
        ));
    }

    #[test]
    fn a_leveled_long_comment_closes_only_at_its_own_level() {
        assert!(is_generated_source(
            b"--[==[\n@generated\n]==]\nreturn {}\n"
        ));
        assert!(is_generated_source(
            b"--[==[\nlicense ]] still open\n@generated\n]==]\nreturn {}\n"
        ));
        assert!(is_generated_source(b"--[=[ @generated ]=] return {}\n"));
        assert!(!is_generated_source(
            b"--[=[ license ]=] local a = 1\n-- @generated\n"
        ));
        assert!(!is_generated_source(
            b"--[= not long\nlocal a = 1\n-- @generated\n"
        ));
    }
}
