use kartta_lang::Banner;

const BANNER: Banner = Banner::new(&["@generated", "DO NOT EDIT"]);
const BYTE_ORDER_MARK: &[u8] = b"\xEF\xBB\xBF";

enum Run {
    Continues,
    OpensBlock,
    Ends,
    Announced,
}

// constraint: only the leading run of comments after the `<?php` tag, and after any byte order mark, is the header, in
// any of the `//`, `#` and `/* */` forms; the first code ends the scan, and only comment text counts, never code after
// a `*/`
pub(crate) fn is_generated_source(source: &[u8]) -> bool {
    let source = source.strip_prefix(BYTE_ORDER_MARK).unwrap_or(source);
    let mut in_block = false;

    for line in source.split(|&byte| byte == b'\n') {
        let mut line = line.trim_ascii();
        if in_block {
            let end = find(line, b"*/");
            if BANNER.marks(&line[..end.unwrap_or(line.len())]) {
                return true;
            }
            let Some(end) = end else {
                continue;
            };
            in_block = false;
            line = line[end + 2..].trim_ascii();
        }
        if let Some(rest) = line.strip_prefix(b"<?php") {
            line = rest.trim_ascii();
        }

        match leading_comments(line) {
            Run::Continues => {}
            Run::OpensBlock => in_block = true,
            Run::Ends => return false,
            Run::Announced => return true,
        }
    }

    false
}

// constraint: `#[` opens a PHP 8 attribute, which is code; a closed `/* */` may be followed by another comment on its
// line, still in the header
fn leading_comments(mut line: &[u8]) -> Run {
    loop {
        if line.is_empty() {
            return Run::Continues;
        }
        if line.starts_with(b"//") || (line.starts_with(b"#") && !line.starts_with(b"#[")) {
            return if BANNER.marks(line) {
                Run::Announced
            } else {
                Run::Continues
            };
        }
        let Some(comment) = line.strip_prefix(b"/*") else {
            return Run::Ends;
        };
        let Some(end) = find(comment, b"*/") else {
            return if BANNER.marks(line) {
                Run::Announced
            } else {
                Run::OpensBlock
            };
        };
        if BANNER.marks(&comment[..end]) {
            return Run::Announced;
        }
        line = comment[end + 2..].trim_ascii();
    }
}

fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack
        .windows(needle.len())
        .position(|window| window == needle)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_attribute_is_code_and_ends_the_header() {
        assert!(!is_generated_source(
            b"<?php\n#[Attribute]\n// @generated\nclass A {}\n"
        ));
        assert!(is_generated_source(b"<?php\n# @generated\nclass A {}\n"));
    }

    #[test]
    fn a_quoted_marker_only_mentions_the_convention() {
        assert!(!is_generated_source(
            b"<?php\n// a `@generated` marker\nclass A {}\n"
        ));
        assert!(is_generated_source(
            b"<?php\n// Code generated by `gen`. DO NOT EDIT.\nclass A {}\n"
        ));
        assert!(is_generated_source(
            b"<?php\n// the `@generated` marker: @generated\nclass A {}\n"
        ));
    }

    #[test]
    fn a_block_comment_spans_lines_until_it_closes() {
        assert!(is_generated_source(
            b"<?php\n/**\n * Licensed.\n *\n * @generated\n */\nclass A {}\n"
        ));
        assert!(is_generated_source(
            b"<?php\n/*\n * Licensed.\n */\n\n// DO NOT EDIT\nclass A {}\n"
        ));
    }
}
