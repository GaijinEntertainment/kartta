#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_builtins_ascend_without_a_repeat_and_name_functions_types_and_exceptions() {
        assert!(BUILTINS.is_sorted_by(|earlier, later| earlier < later));
        for builtin in ["len", "list", "open", "ValueError", "__import__", "anext"] {
            assert!(BUILTINS.binary_search(&builtin).is_ok(), "{builtin}");
        }
    }
}
