const MARKERS: [&[u8]; 2] = [b"@generated", b"DO NOT EDIT"];

// constraint: only the leading run of `#` comments is the header; the first code line ends the scan
pub(crate) fn is_generated_source(source: &[u8]) -> bool {
    let source = source.strip_prefix(b"\xEF\xBB\xBF").unwrap_or(source);
    for line in source.split(|&byte| byte == b'\n') {
        let line = line.trim_ascii();
        if line.is_empty() {
            continue;
        }
        if !line.starts_with(b"#") {
            return false;
        }
        if MARKERS.iter().any(|marker| announces(line, marker)) {
            return true;
        }
    }

    false
}

// constraint: a marker inside a backtick span documents the convention rather than claiming this file follows it
fn announces(line: &[u8], marker: &[u8]) -> bool {
    line.windows(marker.len())
        .enumerate()
        .filter(|(_, window)| *window == marker)
        .any(|(at, _)| {
            line[..at]
                .iter()
                .fold(true, |outside_span, &byte| outside_span ^ (byte == b'`'))
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_quoted_marker_only_mentions_the_convention() {
        assert!(announces(b"# @generated by tooling", b"@generated"));
        assert!(!announces(b"# a `@generated` marker", b"@generated"));
        assert!(announces(b"# see `docs.md`: @generated", b"@generated"));
        assert!(!announces(b"# see `docs.md: @generated", b"@generated"));
    }

    #[test]
    fn the_header_ends_at_the_first_code_line() {
        assert!(is_generated_source(b"\n# DO NOT EDIT\nclass a {}\n"));
        assert!(!is_generated_source(b"class a {\n  # @generated\n}\n"));
        assert!(!is_generated_source(b"# a plain module\nclass a {}\n"));
    }

    #[test]
    fn a_byte_order_mark_opens_the_header() {
        assert!(is_generated_source(
            b"\xEF\xBB\xBF# @generated\nclass a {}\n"
        ));
        assert!(!is_generated_source(
            b"\xEF\xBB\xBFclass a {}\n# @generated\n"
        ));
    }
}
