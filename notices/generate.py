#!/usr/bin/env python3
"""Writes notices/THIRD-PARTY-NOTICES.txt: everything third-party linked into the binary artifacts, with its licence.

Run it from anywhere, with the pinned toolchain's rust-src installed, after a change to Cargo.lock or to the toolchain.
CI runs it and fails when the file it writes differs from the committed one. See design-docs/adr/4.47-binary-notices.md.
"""

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

NOTICES = Path(__file__).resolve().parent
ROOT = NOTICES.parent
ARTIFACTS = ("kartta-mcp", "kartta-ffi", "kartta-node")
# The support matrix of design-docs/adr/4.46-release-scope.md.
TARGETS = (
    "aarch64-apple-darwin",
    "aarch64-unknown-linux-gnu",
    "aarch64-unknown-linux-musl",
    "x86_64-pc-windows-msvc",
    "x86_64-unknown-linux-gnu",
    "x86_64-unknown-linux-musl",
)
LICENCE_FILE = re.compile(
    r"(?:LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)(?!.*\.(?:rs|c|h|json|toml))",
    re.IGNORECASE,
)
# Packages that publish no licence file of their own, with the text taken from their repository at the published commit.
UNPACKAGED = {
    "napi": ["napi-rs.LICENSE"],
    "napi-sys": ["napi-rs.LICENSE"],
    "objc2-core-foundation": ["objc2.LICENSE"],
    "objc2-core-services": ["objc2.LICENSE"],
    "tree-sitter-cpp": ["tree-sitter-cpp.LICENSE"],
    "tree-sitter-lua": ["tree-sitter-lua.LICENSE"],
    "tree-sitter-puppet": ["tree-sitter-puppet.LICENSE"],
    "tree-sitter-ruby": ["tree-sitter-ruby.LICENSE"],
    "tree-sitter-typescript": ["tree-sitter-typescript.LICENSE"],
}
# The standard library's own crates and every crate it links on the support matrix, as its rlibs name them. rust-src
# vendors these under library/vendor beside crates for other targets, which no artifact links.
STD_VENDORED = (
    "addr2line",
    "adler2",
    "cfg-if",
    "gimli",
    "hashbrown",
    "libc",
    "memchr",
    "miniz_oxide",
    "object",
    "rustc-demangle",
)
STD_IN_TREE = ("backtrace", "compiler-builtins", "portable-simd", "stdarch")
ALL = ", ".join(ARTIFACTS)
# Code in an artifact that no package manifest names.
UNMANIFESTED = (
    ("The Rust standard library", "MIT OR Apache-2.0", ALL, ["rust.COPYRIGHT", "rust.LICENSE-MIT"]),
    ("musl 1.2.5", "MIT", "kartta-mcp, on Linux with musl", ["musl.COPYRIGHT"]),
    ("LLVM libunwind", "Apache-2.0 WITH LLVM-exception", "kartta-mcp, on Linux with musl", ["llvm.LICENSE"]),
    ("endian.h of the tree-sitter runtime", "public domain", ALL, ["tree-sitter.endian.h"]),
)


def run(*command):
    return subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def linked(artifact, target):
    """Yields the registry packages linked into `artifact`, neither proc macros nor build tools."""
    walk = ("-e", "normal,no-proc-macro", "--prefix", "none", "-f", "{p}")
    tree = run("cargo", "tree", "--locked", "-p", artifact, "--target", target, *walk)
    for line in tree.splitlines():
        name, version, *rest = line.split()
        if not rest or rest[0] == "(*)":
            yield name, version[1:]


def licence_files(directory):
    """Every licence file under `directory`: a package's nested one covers code it vendors, as ICU's in tree-sitter."""
    return sorted(path for path in directory.rglob("*") if LICENCE_FILE.match(path.name) and path.is_file())


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")


class Notices:
    def __init__(self):
        self.rows = []
        self.texts = defaultdict(list)

    def add(self, label, licence, used_in, sources):
        """`sources` are (name to show, file to read) pairs, and equal texts share one section."""
        self.rows.append((label, licence, used_in))
        for shown, path in sources:
            self.texts[read(path)].append(f"{label} ({shown})")

    def render(self):
        width = max(len(row[0]) for row in self.rows)
        lines = [
            "Third-party notices of the kartta binary artifacts: kartta-mcp, libkartta_ffi.a and the Node addon.",
            "",
            "Generated by notices/generate.py from Cargo.lock and the pinned toolchain. Do not edit.",
            "It covers every target of the support matrix, so a build for one target links a subset of what is listed.",
            "Each row names the artifacts that link the component. The licence texts follow the list.",
            "",
        ]
        lines += [f"{row[0]:<{width}}  {row[1]}  [{row[2]}]" for row in sorted(self.rows)]
        for text, users in sorted(self.texts.items(), key=lambda item: sorted(item[1])):
            lines += ["", "=" * 80, *sorted(users), "=" * 80, "", text]
        return "\n".join(lines) + "\n"


def add_crates(notices):
    users = defaultdict(list)
    for artifact in ARTIFACTS:
        packages = {package for target in TARGETS for package in linked(artifact, target)}
        for package in packages:
            users[package].append(artifact)
    metadata = json.loads(run("cargo", "metadata", "--locked", "--format-version", "1"))
    manifests = {(package["name"], package["version"]): package for package in metadata["packages"]}
    unlicensed = []
    for (name, version), artifacts in users.items():
        package = manifests[name, version]
        directory = Path(package["manifest_path"]).parent
        sources = [(str(path.relative_to(directory)), path) for path in licence_files(directory)]
        sources += [(text, NOTICES / "texts" / text) for text in UNPACKAGED.get(name, ())]
        if not sources:
            unlicensed.append(name)
        notices.add(f"{name} {version}", package["license"], ", ".join(artifacts), sources)
    if unlicensed:
        sys.exit(f"no licence file, add the upstream text to UNPACKAGED: {', '.join(sorted(unlicensed))}")


def add_standard_library(notices):
    library = Path(run("rustc", "--print", "sysroot").strip()) / "lib/rustlib/src/rust/library"
    if not library.is_dir():
        sys.exit("rust-src is missing: run `rustup component add rust-src`")
    for name in STD_IN_TREE:
        path = library / name
        sources = [(str(file.relative_to(path)), file) for file in licence_files(path)]
        notices.add(f"{name} of the standard library", "see its text", ALL, sources)
    for name in STD_VENDORED:
        path = next(library.glob(f"vendor/{name}-[0-9]*"))
        sources = [(file.name, file) for file in licence_files(path)]
        licence = re.search(r'^license = "(.*)"$', (path / "Cargo.toml").read_text(encoding="utf-8"), re.MULTILINE)
        notices.add(path.name.replace(f"{name}-", f"{name} "), licence[1], ALL, sources)


def main():
    notices = Notices()
    add_crates(notices)
    add_standard_library(notices)
    for label, licence, used_in, texts in UNMANIFESTED:
        notices.add(label, licence, used_in, [(text, NOTICES / "texts" / text) for text in texts])
    (NOTICES / "THIRD-PARTY-NOTICES.txt").write_bytes(notices.render().encode())


if __name__ == "__main__":
    main()
